def question(number, stem, options, correct, star_position=None):
    formatted_options = [f'{i}. {text}' for i, text in enumerate(options, 1)]
    data = {
        'number': number,
        'stem': stem,
        'options': formatted_options,
        'correct': correct,
        'correctOption': formatted_options[correct - 1]
    }
    if star_position is not None:
        data['starPosition'] = star_position
    return data


def section(section_type, title, title_en, page_ref, instruction, rows, answers, star_positions=None):
    def format_target(text):
        reading = USAGE_READINGS.get(text)
        return f'<ruby>{text}<rt>{reading}</rt></ruby>' if reading else text

    def format_stem(stem):
        if section_type != 'usage':
            return stem
        return format_target(stem)

    def format_options(stem, options):
        if section_type != 'usage':
            return options
        variants = [stem]
        if stem.endswith('る'):
            variants.extend([stem[:-1] + ending for ending in ('った', 'って', 'て', 'た')])
            if stem in USAGE_NEGATIVE_FORMS:
                variants.append(USAGE_NEGATIVE_FORMS[stem])
        elif stem.endswith('い'):
            variants.extend([stem[:-1] + ending for ending in ('く', 'かった', 'くて')])
        elif stem.endswith('な'):
            variants.append(stem[:-1])
        variants.sort(key=len, reverse=True)

        formatted = []
        for option in options:
            marked = option
            for variant in variants:
                replacement = f'<u>{format_target(variant) if variant == stem else variant}</u>'
                marked = marked.replace(variant, replacement)
            formatted.append(marked)
        return formatted

    questions = []
    for i, (stem, options) in enumerate(rows, 1):
        formatted_options = format_options(stem, options)
        star_position = star_positions[i - 1] if star_positions else None
        questions.append(question(i, format_stem(stem), formatted_options, answers[i - 1], star_position))

    return {
        'type': section_type,
        'title': title,
        'titleEn': title_en,
        'pageRef': page_ref,
        'instruction': instruction,
        'questions': questions
    }

