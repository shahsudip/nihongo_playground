def update_usage():
    for cid, qmap in USAGE_EXPLANATIONS_N3_W3.items():
        fpath = f"src/data/zenkamoku_n3/{cid}.json"
        if not os.path.exists(fpath):
            continue
        with open(fpath, "r", encoding="utf-8") as f:
            data = json.load(f)
        
        for sec in data.get("subSections", []) + data.get("sections", []):
            if sec.get("title") == "用法" or sec.get("type") == "usage":
                for q in sec.get("questions", []):
                    num = q.get("number")
                    if num in qmap:
                        q["explanation"] = qmap[num]
        
        with open(fpath, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"Injected usage explanations into {cid}")

update_usage()
